def latin_ratio(t):
    body = [c for c in t if not c.isspace()]
    if not body:
        return 0.0
    return sum(1 for c in body if c.isascii() and c.isalpha()) / len(body)


#: 「连续 3 个以上英文单词」的粗探针 —— 用来诊断"还有没有整句英文残留"。
#: 单词级（`[ticked]`、专名）不会命中，整句会。**这是诊断不是判据**（判据在 apply 侧）。
EN_RUN = re.compile(r'[A-Za-z][A-Za-z\'\-]*\s+[A-Za-z][A-Za-z\'\-]*\s+[A-Za-z][A-Za-z\'\-]*')


def main(argv):
    apply = '--apply' in argv
    raw = io.open(SRC, encoding='utf-8', newline='').read()
    # ★★★ 必须 `keepends=True` + 原位替换：这份人设是**混合 EOL**
    #   （121 行里只有 112 个 CRLF，另外 9 行是纯 LF）。
    #   第一版用 `splitlines()` + `'\r\n'.join()` 重建 ⇒ 把 9 个 LF 行也改成了 CRLF，
    #   于是「尾部运行口径块逐字不变」直接报红（尾块本身没动，是**分隔符**被改了）。
    lines = raw.splitlines(keepends=True)
    n0 = len(lines)
    assert ''.join(lines) == raw, 'keepends 拼回不等于原文 —— 拒绝继续'

    # ---- 先把所有锚验一遍，一条不过就整体不动（不许写一半）----
    print('=== 锚校验（行号 + 行首锚双定位）===')
    bad = []
    for ln, anchor, _new in EDITS:
        if ln < 1 or ln > n0:
            bad.append('L%d 越界（共 %d 行）' % (ln, n0))
            continue
        hit_all = raw.count(anchor)
        at_line = (lines[ln - 1].count(anchor) == 1)
        if not at_line or hit_all != 1:
            bad.append('L%d 锚 %r 本行命中=%s 全文出现 %d 次' % (ln, anchor[:14], at_line, hit_all))
    if bad:
        print('FAIL: %d 处锚对不上，一条都不改：' % len(bad))
        for b in bad:
            print('  - ' + b)
        return 3
    print('  全部 %d 条锚在本行命中一次、全文唯一  OK' % len(EDITS))

    # ---- 幂等：同一行不许被两张表同时改 ----
    seen = set()
    for ln, _a, _n in EDITS:
        if ln in seen:
            print('FAIL: L%d 在替换表里出现两次' % ln)
            return 3
        seen.add(ln)

    out = list(lines)
    same_cnt = 0
    for ln, _anchor, new in EDITS:
        eol = EOL_RE.search(out[ln - 1])
        eol = eol.group(1) if eol else ''
        if EOL_RE.sub('', out[ln - 1]) == new:
            same_cnt += 1
        out[ln - 1] = new + eol          # ★ 行尾**原样**带过去，不改 EOL
    if same_cnt:
        print('  注意 %d 行已是目标内容（重复执行过？）' % same_cnt)
    new_raw = ''.join(out)

    # ---- 结构自检 ----
    print()
    print('=== 结构自检 ===')
    ok = True
    same_n = (len(new_raw.splitlines()) == n0)
    ok &= same_n
    print('  ① 行数 %d → %d  %s' % (n0, len(new_raw.splitlines()), 'OK' if same_n else 'FAIL'))

    tail_old = raw[raw.index(TAIL_ANCHOR):]
    tail_new = new_raw[new_raw.index(TAIL_ANCHOR):]
    same_tail = (tail_old == tail_new)
    ok &= same_tail
    print('  ② 尾部运行口径块逐字不变（%d 字）  %s' % (len(tail_old), 'OK' if same_tail else 'FAIL'))

    lr0, lr1 = latin_ratio(raw), latin_ratio(new_raw)
    print('  ③ 拉丁占比 %.0f%% → %.0f%%' % (lr0 * 100, lr1 * 100))

    def sec(txt):
        i = txt.index('【示例反应】')
        j = txt.find('\n---', i)
        return txt[i:j if j > 0 else len(txt)]

    s0, s1 = sec(raw), sec(new_raw)
    l0, l1 = latin_ratio(s0), latin_ratio(s1)
    print('  ④ 示例段 %d 字(拉丁 %.0f%%) → %d 字(拉丁 %.0f%%)'
          % (len(s0), l0 * 100, len(s1), l1 * 100))
    c4 = (l1 < 0.10)
    ok &= c4
    print('     示例段拉丁 < 10%%  %s' % ('OK' if c4 else 'FAIL'))

    # ⑤ 残留整句英文诊断（专名与 [ticked] 类不算）
    runs = EN_RUN.findall(s1)
    print('  ⑤ 示例段残留「连续≥3 英文单词」：%d 处 %r' % (len(runs), sorted(set(runs))[:6]))
    c5 = (len(runs) == 0)
    ok &= c5
    print('     零残留  %s' % ('OK' if c5 else 'FAIL'))

    if not ok:
        print('\nFAIL: 结构自检未过，不写盘。')
        return 3

    print()
    if not apply:
        print('（dry：未写盘。加 --apply 落盘到 %s）' % os.path.relpath(DST, ROOT))
        return 0
    if not os.path.isdir(OUT_DIR):
        os.makedirs(OUT_DIR)
    with io.open(DST, 'wb') as fh:
        fh.write(new_raw.encode('utf-8'))
    back = io.open(DST, encoding='utf-8', newline='').read()
    print('已写盘 %s（回读一致 = %s）' % (os.path.relpath(DST, ROOT), back == new_raw))
    return 0 if back == new_raw else 3


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
