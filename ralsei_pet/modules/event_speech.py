#   · `_SCENE_ACT_VERBS` 场景交互 → **删，不说**
#   · `_INNER_ACT_VERBS` 内在活动 → **删，不说**   ← 本轮新增
#   · `_SELF_ACT_VERBS`  外在表现 → **删，说成旁白**
#
# ⚠️ 为什么不把它并进 `_EXT_ACT_DENY`
#   那张表是**否定表**（命中 = "不认成动作"），命中后括号会**原样留在台词里**。
#   而这次要的是**删掉**，方向相反，只能另立一张。
# ⚠️ 为什么用"整段匹配 + 12 字余量"而不是包含匹配
#   `（我想想该怎么说）` 是**合法的第一人称心里话**，`C19`/`A22c` 都钉着它必须留下。
#   整段匹配要求内在动词**在开头**（前面只允许挂程度副词），`我…` 开头的不命中，
#   与既有契约天然不冲突。
# ---------------------------------------------------------------------------
_INNER_ACT_VERBS = (
    u'想|想着|想了想|想到|寻思|琢磨|思考|沉思|思量|思忖|'
    u'回忆|回想|记起|追忆|'
    u'犹豫|纠结|盘算|猜测|心想|暗想|暗道|'
    u'考虑|掂量|权衡|意识到|察觉|'
    # 下两位来自 `_BARE_MOOD` / `_NARRATION_INNER` 已经会删的那批：
    # 它们在**前几道闸**就被删并 `_note` 了，这里只负责"别把它们播成旁白"。
    u'沉默|停顿')

_INNER_ACT_RE = re.compile(
    u'^\\s*(?:%s)?\\s*(?:%s)[^）)＊*]{0,12}\\s*$'
    % (_ACTION_MODIFIERS, _INNER_ACT_VERBS))


def is_inner_act(act):
    """这段括号内容是不是**内在活动**（⇒ 删掉、也**不出旁白**）。

    用户口径：`想一想这类的不留 … 每一个想一想都播那就太麻烦了`
    ★ 返回 True 的两件事一起做：末闸**删掉**、显示层**不播**。
      两个调用点共用本函数 —— 免得"删了却还在旁边念一行"。
    """
    s = (act or u'').strip() if isinstance(act, str) else u''
    if not s:
        return False
    return bool(_INNER_ACT_RE.match(s))


# 任意括号对（用于叙述形态的清理）
# ★★★ 113轮e：原 `{0,40}` 上限太窄，模型写的旁白常超 40 字 ⇒ 丙闸根本没机会判。
#   `[^）)]` 已保证不跨括号对，放宽到 200 不会吞掉后续台词。
_ANY_PAREN_RE = re.compile(r'[（(]([^）)]{0,200})[）)]')


#: ★★★ 第113轮f：括号里的**引号片段** = 角色真正说出口的话。
#: 实测 susie 48 轮 48 处括号里 **47 处**是 `（你皱了皱眉，“其实我挺想去的。”）`
#: 这种形态 —— 旧护栏删掉整段，等于把她要说的话一起扔了。
#: 所以先「救」：把引号里的话提出来当台词，括号里的旁白部分再按原规则丢。
_QUOTED_SPAN_RE = re.compile(
    r'[\u201c\u0022\u300c]([^\u201c\u201d\u0022\u300d]{1,300})[\u201d\u0022\u300d]')


def _rescue_quoted(m):
    """括号内有引号 ⇒ 返回引号里的台词；没有引号 ⇒ 原样返回（交给后面几道闸）。"""
    inner = m.group(1) or ''
    spans = [s.strip() for s in _QUOTED_SPAN_RE.findall(inner)]
    spans = [s for s in spans if s]
    if not spans:
        return m.group(0)
    return ''.join(spans)


#: ★★★ 第189轮（用户口径：「笑声也就是角色发出来的声音**直接显示**就好，
#:   这也是原作的一种特色」）：发声类括号**不删，改成直出**。
#:   `（笑声：Geh ha ha ha ha）` → `Geh ha ha ha ha`；`（NYEH HEH HEH!）` → `NYEH HEH HEH!`。
#: ★★ 实测边界（`_evidence/measure189.json`）：419 条 `ACTION_PAREN` 跑完护栏后
#:   仍在的括号里，"发声类"只有 **30 处 / 4 种形态**：`（NYEH HEH HEH!）` 19、
#:   `（笑声：Geh ha ha ha ha）` 5、`（NYEH HEH HEH！）` 5、`（NYEH HEH HEH!)` 1。
#:   而 `（SANS! STOP BEING LAZY!）` 4 处**含实词**，是台词错位不是发声 ⇒ 必须留着
#:   （判据 `B1` 专门钉这一条，防止有人把"英文大写"当成笑声）。
_VOICE_LABEL_RE = re.compile(
    u'^\\s*(?:笑\\s*声|笑|声音|音效|语气声)\\s*[:：]\\s*(\\S.*)$', re.S)
#: `（笑声（哈））` 这种套一层的写法
_VOICE_WRAP_RE = re.compile(
    u'^\\s*(?:笑\\s*声|声音|音效)\\s*[（(]\\s*(\\S.*?)\\s*[)）]\\s*$', re.S)
#: 整段就是中文拟声（语料里 0 例，属**预防性覆盖**；判据里标了 no-data）
_ONO_RE = re.compile(u'^[哈嘿嘻呵嚯哇呜啊嗯哼哦呀唉]{2,}$')
_EN_TOK_RE = re.compile(u"[A-Za-z']+")
#: 英文"笑声词"白名单。★ 只收纯发声音节，**不收**任何实词 ——
#:   `STOP/BEING/LAZY` 这类不在表里 ⇒ `（SANS! STOP BEING LAZY!）` 天然不命中。
_LAUGH_EN = frozenset([
    'ha', 'haa', 'haha', 'hahaha', 'hahahaha', 'heh', 'hehe', 'heheh',
    'hehehe', 'heheheh', 'nyeh', 'nyehh', 'mweh', 'mwehehe', 'mweheheh',
    'geh', 'geheh', 'huh', 'ho', 'hoho', 'hohoho', 'hah', 'hee', 'heehee',
    'teehee', 'nyah', 'nya', 'lah', 'mwah', 'psst', 'lol'])


def _rescue_voice(m):
    """己闸替换：括号内容是**发声** ⇒ 返回声音本体（直出）；否则原样返回。

    ★ 三支：① `标签：内容` ② 整段中文拟声 ③ 整段英文笑声词。
      三者都不命中 ⇒ `m.group(0)`，交给甲/丙/戊照旧处理。
    """
    inner = (m.group(1) or '').strip()
    mo = _VOICE_LABEL_RE.match(inner) or _VOICE_WRAP_RE.match(inner)
    if mo:
        payload = (mo.group(1) or '').strip()
        return payload or m.group(0)
    if _ONO_RE.match(inner):
        return inner
    toks = _EN_TOK_RE.findall(inner)
    if toks and all(x.lower() in _LAUGH_EN for x in toks):
        return inner
    return m.group(0)


def strip_action_parentheticals(text, sink=None, pause_sink=None):
    """删掉台词里夹带的「括号旁白」，返回剩下的台词。

    ★★★ 第190轮新增 `sink`（用户口径：「括号里的内容也就是表情和动作，
    用人物动画和表情头像表示」⇒ 删掉的那段不能扔，要拿去驱动表情）。

        _acts = []
        clean = strip_action_parentheticals(text, sink=_acts)   # _acts 里是原片段

    ★★★ 第190轮续二新增 `pause_sink`（用户口径：「**但一定要留时间**，
    如果有，那就用动画表示哦」）：

        _inner = []
        clean = strip_action_parentheticals(text, sink=_acts, pause_sink=_inner)

      **内在活动**（`想了想` / `犹豫` / `沉默片刻`）删掉之后：
        · 不进 `sink` —— 它没有表情可换，也不许变成旁白（"每一个想一想都播太麻烦了"）
        · 进 `pause_sink` —— 显示层据此**留一段停顿**，有对应动画就用动画演
      两个通道**分开**是刻意的：合成一个通道，显示层就分不清"该说话"还是"该停顿"。

    返回值的语义**完全不变**（字符串）⇒ 既有调用方零影响。

    五道闸合起来覆盖括号的全部已知形态：
      己) **发声直出**（第189轮补）：括号内容**整段是声音**（`（笑声：X）` /
          `（NYEH HEH HEH!）`）→ **不删，把声音本体留下**（用户口径："笑声音效直接显示，
          这也是原作的一种特色"）
      甲) 括号内以**动作/发声动词**开头 → `_ACTION_PAREN_RE`（老闸）
      乙) 句首括号 → `looks_like_narration`（老闸，走"整句作废"）
      丙) **描述性旁白**（本闸，第27轮补）：括号内容是"从外部描述自己"的
          → 清掉；是**第一人称心里话**的 → 原样保留（判据见 `_NARRATION_INNER`）
      戊) **裸情绪标签**（第188轮补）：括号内容**整段**是「修饰语+情绪词+后缀」
          → 清掉（`（笑）` / `（微笑）` / `（苦笑）`；判据与实证见 `_BARE_LABEL_RE` 上方）

    ⚠️ 与 `_ACTION_PAREN_RE` 的分工：那个按**动作动词**抓，
    本闸按**状态描述词**抓；两者都可能命中同一段，先跑甲闸再跑丙闸不会重复删。

    返回空串的两类（语义都是"这条不能作为台词用"，由调用方按判退处理）：
      * 整句只有括号内容（删完什么都不剩）
      * 删完只剩标点/空白（没有任何实义字符）

    注意：这里**不做** `looks_like_narration` 那类"整句作废"的判断 ——
    句首括号的整句叙述交给那道老闸，五道闸分工不同（见上方注释）。
    """
    if not isinstance(text, str):
        return ""
    if not text:
        return ""

    def _note(removed):
        """记下**真的被删掉**的那一段（供上层驱动表情 / 停顿）。

        ★ 只在`各闸确实删了东西`时调用 —— 不能在函数末尾统一猜"大概删了什么"，
          否则拿到的是猜出来的旁白，不是实际删掉的。
        ★ 空串/纯空白/纯标点不记（`（）` 这种没有动作含义）。
        ★★★ 第190轮续二：**内在活动改道去 `pause_sink`**。
          把所有闸都塞进这一个出口，而不是逐个闸判断 —— 内在词会从甲/丙/戊
          **任意一道**漏出来（`犹豫`走戊、`沉默片刻`走丙、`想了想`走末闸），
          逐个改闸等于留一堆漏点；从出口分流则天然全覆盖。
        """
        if sink is None and pause_sink is None:
            return
        s = (removed or "").strip().strip("()（）[]【】")
        s = s.strip()
        if not (s and re.search(r'[0-9A-Za-z\u4e00-\u9fff]', s)):
            return
        if is_inner_act(s):
            if pause_sink is not None:
                pause_sink.append(s)
            return
        if sink is not None:
            sink.append(s)

    def _kill_narration(m):
        """丙闸替换：括号内容是"描述自己"的 → 清掉；是心里话 → 原样留。"""
        inner = (m.group(1) or "").strip()
        if (_NARRATION_INNER.match(inner)
                or _SECOND_PERSON_NARRATION.match(inner)
                or _QUOTED_IN_PAREN.search(inner)):
            _note(inner)
            return ""                  # 描述性旁白 → 清掉
        return m.group(0)              # 其余（含第一人称心里话）→ 原样保留

    def _kill_bare_label(m):
        """末闸：括号内容**整段**是裸情绪标签 / 残留的外在表现 → 清掉；其余原样留。

        ★ 只认"整段等形态"，所以 `（笑不出来）`（`不出来` 不在后缀集）与
          `（微笑切面条）`（`微笑` 后面跟的是名词）都不会命中。
        ★★ 第190轮续：多认**残留的外在表现**两类（见上方 `_SCENE_ACT_VERBS`
          那张长注释）。场景交互与角色自表示**都删**，区别只在显示层：
          场景类不出旁白（场景自己会表现），自表示类才说成旁白。
        """
        inner = (m.group(1) or "").strip()
        # ★★ 第190轮续二：**内在活动**（`（想了想）` / `（犹豫）` / `（沉思片刻）`）
        #   ⇒ 删掉；但要**留下时间**（用户：`但一定要留时间如果有，那就用动画表示哦`）。
        #   `_note()` 内部会把它改道到 `pause_sink`，所以这里照常记一笔即可 ——
        #   记了它不会变成旁白（`sink` 收不到），只会让显示层知道"这里该停顿一下"。
        #   ★ 必须排在最前：`（犹豫）` 同时能命中下面的 `_BARE_LABEL_RE`，
        #     先判内在，才能保证它走停顿通道而不是表情通道。
        if is_inner_act(inner):
            _note(inner)
            return ""
        if _BARE_LABEL_RE.match(inner):
            _note(inner)               # ★ 裸情绪标签正是最想要的信号（（笑）（微笑））
            return ""
        if is_scene_act(inner) or is_self_act(inner):
            _note(inner)               # ★ 外在表现也删；显示层再按类分流
            return ""
        return m.group(0)

    def _kill_action(m):
        """甲闸替换：括号内以动作/发声动词开头 → 删掉并记录。"""
        _note(m.group(1) if m.groups() else m.group(0))
        return ""

    _before = text
    # 己闸（第189轮）：**发声直出** —— `（笑声：X）` / `（NYEH HEH HEH!）` 把声音本体留下。
    #   ⚠️ 排在**最前**：发声不是"该删的旁白"，也不是"该救的引号台词"，
    #      它是一条独立的"转译"规则。放最前可以保证后面四道闸对**其余**括号
    #      的行为逐字不变（回归面最小）。
    #   ★★ 第190轮：己闸**不删内容、只转译**，但它转译掉的那个括号正是情绪信号
    #      （`（NYEH HEH HEH!）` 是 asgore 的招牌大笑）⇒ 必须补记一笔。
    #      ⚠️ 用**先扫一遍再 sub**，而不是把回调包成闭包 —— `_rescue_voice`
    #      必须保持**模块级裸名**：老锁 `check189 D3` 钉着"不是函数内闭包"，
    #      `probe188.py` 靠 monkeypatch `E._rescue_voice` 关闸。
    #      包一层闭包会让这两处静默失效（第190轮真踩过，check188/189 双红）。
    if sink is not None:
        for _mv in _ANY_PAREN_RE.finditer(text):
            if _rescue_voice(_mv) != _mv.group(0):
                _note(_mv.group(0))
    t = _ANY_PAREN_RE.sub(_rescue_voice, text)
    # 丁闸（第113轮f）：**先救出台词** —— 括号里有引号的，把引号内容提出来，
    #   否则后面几道闸会把它连旁白一起删掉（susie 98% 的括号都是这种）。
    #   ⚠️ 顺序是硬约束：必须在甲/丙/戊之前，否则台词早被删没了。
    t = _ANY_PAREN_RE.sub(_rescue_quoted, t)
    # 甲闸：动作旁白（括号内以动作动词开头）
    t = _ACTION_PAREN_RE.sub(_kill_action, t)
    # 丙闸：描述性旁白
    t = _ANY_PAREN_RE.sub(_kill_narration, t)
    # 戊闸（第188轮）：**裸情绪标签**（`（笑）` / `（微笑）` / `（苦笑）`）。
    #   ⚠️ 必须排在丁闸之后：`（笑"我真的没事"）` 要先救出引号内容，
    #      否则整段被当标签删掉，台词跟着没了。
    #   排在最末还有第二个理由：甲/丙对他们各自的目标保持**逐字不变**的行为，
    #   戊只清理「活到这一步还剩的」括号 —— 回归面最小。
    t = _ANY_PAREN_RE.sub(_kill_bare_label, t)
    if t != _before:
        # 删掉一段后收拾残局：
        #   「我在呢。*轻轻敲了敲键盘* 要不要先喝水」→「我在呢。要不要先喝水」
        #   「…藏在心里。\n\n（停顿了一下）\n你说的」→ 不留三连换行
        t = re.sub(r'[ \t]{2,}', ' ', t)
        t = re.sub(r'([。！？…，、；：])[ \t]+', r'\1', t)
        t = re.sub(r'\n{3,}', '\n\n', t)
        t = t.lstrip('，,、。；;：: \t')
        t = t.strip()
    if not re.search(r'[0-9A-Za-z\u4e00-\u9fff]', t):
        return ""
    return t


#: 句首"纯迟疑词"—— 开口前先垫的那一口气。
#: ★★ **只收这 5 个**，故意不收 `啊/唉/哎`：那三个在中文里是**真感叹**
#:    （「哎呀，走了一万多步挺不错的！」），削掉会伤语气，反而更像模板。
#:    判据与实测量纲一致：`_evidence/ab128.json` 里 `head_pure` 就是按这 5 个字数的。
_HEAD_HES = u'嗯诶哦呃唔'
#: ★ 用 `(?:…)+` 而不是单发：实测真机会吐「诶、诶？！」「嗯、嗯……」这种
#: **一顿一迟疑**的连环（`assistant` 的人味改造样例里就有），只削第一簇会
#: 留下第二个「诶」—— 指标看着降了，屏幕上还是那口气。
_HEAD_HES_RE = re.compile(
    u'^(?:[%s]{1,3}\\s*(?:…+|\\.{3,}|—+|－+|~+|，|,|、|？|\\?|！|!)?\\s*)+' % _HEAD_HES)
#: 削完可能露出一个孤零零的标点（`诶、诶？！` → `！`），一并清掉
_LEAD_PUNCT = u'！!？?，,、。；;：: \t'

#: ★★ 128 续（用户口径「不能为 0%」）：本回合**是否放行**句首那一簇。
#:   为什么是模块级开关而不是函数参数：流式层（`_sanitize_partial_reply`，staticmethod）
