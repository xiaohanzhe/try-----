#:   而两处**必须看到同一个决定**（否则"流式留着、收尾削掉"＝字缩回去）。
#:   **默认 False ＝ 削**，与 128 轮行为一字不差 ⇒ 没设过的调用方（含全部探针）不变。
_HES_ALLOW = {'on': False}


