def _eat_sentence_end(t, i):
    """把紧跟其后的连续句末标点一起吃掉（`……` / `！！` / `？！` 不许切一半）。

    ★ 第136轮：`…` 进了 `_SENTENCE_ENDS` 之后必须配套这一步 ——
      否则 `……` 会只剩一个 `…`（`是吧…`），`诶？！` 会变成 `诶？`（丢一个感叹号）。
      `\\n` 不参与吃（换行后面接标点不算"连续标点"）。
    """
    if i >= len(t) or t[i] == '\n':
        return i
    while i + 1 < len(t) and t[i + 1] in _SENTENCE_ENDS and t[i + 1] != '\n':
        i += 1
    return i


def _sentence_ends(t):
    """`t` 里所有**合格的**句末位置（下标已吃掉连续标点），升序、去重。

    ★★★ 第145轮：`first_sentence` 与 `fit_sentences` 原来各自抄了一遍
      "扫 `_SENTENCE_ENDS` + 吃连续标点 + 去重"这段循环 —— **同一份规则两处算**，
      正是本项目最贵的坑。加 `.` 的过滤规则必须两边一致，所以合成这一处。

    ★ `.` 的过滤规则（与 `MIN_FIRST_CHARS` 同源）：
      `.` 前面已经有 **≥ MIN_FIRST_CHARS 个字**，它才够格当句末。理由：
        · 缩写点：`Mr. Smith` / `J. Doe` —— 头只有 2~3 个字，不是句末，
          而事件链上限 24 字，一个 `Mr.` 就能把整行吃掉；
        · 开头的省略号：`...H-H-HERE` —— `_eat_sentence_end` 会吃掉连续点，
          头是空的，同样不是句末；
        · 小数点：`3.14` —— 后面紧跟数字，显式排除（不靠 MIN 兜，因为
          `一共有 1234.5` 这种头已经很长了）。
      ★ 中文侧几乎不影响（中文用 `。`），实测见 `lead145.json` 的 `ab` 段。
    """
    out = []
    for i in sorted(i for i, ch in enumerate(t) if ch in _SENTENCE_ENDS):
        j = _eat_sentence_end(t, i)
        if t[i] == '.':
            if j + 1 < len(t) and t[j + 1].isdigit():
                continue                      # 小数点：`3.14`
            if len(t[:j + 1].strip()) < MIN_FIRST_CHARS:
                continue                      # 缩写点 / 开头的省略号
        if not out or j != out[-1]:
            out.append(j)
    return out


def _hard_cut(t, max_chars):
    """压到 `max_chars` 内。切点落在**单词中间**时，先退到最后一个空格。

    ★ 第147轮：24/40 字里一个句末标点都没有的英文（`hehe that tickles so mu|ch`）
      原来直接 `t[:max_chars]` ⇒ 用户看到的是一个**残词**。
      退到最后一个空格能把词收完整，代价实测很小：
      24 字链 134/135 、40 字链 100/100 条能整词收尾，平均只少 **3.9 / 4.2** 个字
      （最短还留 14 / 28 字；`_evidence/measure147.json`）。
    ★ 退让底线两条（**数据选的，不是我拍的**）：
      ① 留下 ≥ `MIN_FIRST_CHARS`（否则退得只剩几个字，比硬截更难看）；
      ② 留下 ≥ 半个预算（`len(keep) * 2 >= max_chars`）—— 退让不许吃掉一半以上。
      阈值扫描：ratio 0/0.3/0.4/0.5 结果完全一致，0.6 起开始少收（135→133→128），
      所以取 0.5：该收的都收了，也挡得住“唯一空格在最前面”的极端。
    ★ **必须限 ASCII**（第147轮实测逼出来的）：`str.isalnum()` 对 CJK 也是 True，
      用它判“切在词中”会把**每一次中文硬截**都当成切在词中 ⇒ 退到空格
      （往往落在英文人名前）⇒ 白丢 4~8 个汉字。用 `isalnum()` 时中文输出变了
      **151 / 57 条**，改成 ASCII 白名单后归 **0**（`_evidence/ab147.json` 里 `zh_changed`）。
    ★ 三处调用（`first_sentence` 一处、`fit_sentences` 两处）共用本函数 ——
      原来那三处各抄一遍，同一份规则三处算。
    """
    if len(t) <= max_chars:
        return t
    cut = t[:max_chars].rstrip(_HARD_CUT_TAIL)
    # 切点两侧都是 **ASCII** 词字符 ⇒ 那个词被劈成两半（中文没有词边界，不参与）
    if cut and len(cut) < len(t) and cut[-1] in _WORDY and t[len(cut)] in _WORDY:
        sp = cut.rfind(u' ')
        if sp > 0:
            keep = cut[:sp].rstrip(_HARD_CUT_TAIL)
            if len(keep.strip()) >= MIN_FIRST_CHARS and len(keep) * 2 >= max_chars:
                return keep
    return cut


def first_sentence(text, max_chars=EVENT_MAX_CHARS):
    """取第一句并压到 max_chars 内；取不到实义字符就返回空串。

    ★★ 第135轮：切点改成**取文本里最靠前的那个句末标点**。
      原来按标点**类型**优先级挑（`。`→`！`→`？`→`!`→`?`→`\\n`，看哪个类型先出现在文里，
      再用它的第一个下标切）。于是"第一句是问句、后面某句有句号"时，切点被推到
      **后面那句的句号**上，再硬截 max_chars ⇒ 截在半个句子上，直接显示成吊尾巴的坏台词。
      真机证据（第131轮 3 条长回复，其中 2 条是这种形状）：

        raw = 「你说的是坏消息吗？\\n\\n你说的是坏消息的时候我不该用亮起来的开头，…。」
        old = 「你说的是坏消息吗？\\n\\n你说的是坏消息的时候我不该」   ← 24 字，断在"我不该"
        new = 「你说的是坏消息吗？」                                  ← 9 字，完整

      取证：`code-quality-audit/第135轮-事件截断吊尾巴/_tools/diag135.py`（旧/新逐条对照）。
      实测影响面：42 条真机事件回复**逐字不变**（它们本来就短），只有长回复变干净。

    ★ `MIN_FIRST_CHARS` 的语义**原样保留**：若没有任何切点够长，而全文又没超上限，
      就整句保留 —— 这一条是真机逼出来的（「嗯？发生了什么吗？」不能被切成 2 个字的「嗯？」）。
      新写法里它落在"找不到合格切点"那个分支上，不要顺手删掉。

    ★ 与 `main.start_autonomous_speech` 里那段内联截断**不是同一份实现**：
      那边 sep 顺序是 `\\n` 优先、上限 40 字、没有 MIN 规则。原注释写的"同源"是假断言，
      第135轮改正。两边口径要不要统一登记在 §135 报告，本轮**不动那条链**。

    注意：markdown / 自问自答 / 车轱辘话由 `RalseiPet._clean_ai_reply` 在更上游处理，
    这里只管"长度与句数" —— 两层规则的分工不要混（S8 的教训：规则必须单一真源）。
    """
    if not isinstance(text, str):
        return ""
    t = text.strip()
    if not t:
        return ""
    t = t.strip('"\'“”「」『』《》').strip()
    if not t:
        return ""
    # ★★ 切点规则（第135轮）：**句号仍然是"一个想法结束了"的边界**，
    #   但句号之前若还有更早的句末标点、且那一句已经够长，就用更早的那个。
    #   三条分支，每条都有判据/真机样本撑着：
    #     ① 有句号 ⇒ 只在"句号及之前"的切点里挑第一个够长的；都不够长就用句号本身
    #        （`诶？！好舒服呀。后面还有好多话要说呢。` ⇒ `诶？！好舒服呀。`）；
    #     ② 没句号 ⇒ 只看**第一个**句末标点，够长就切、太短就整句保留
    #        （`哎呀！别捏我的耳朵！好痒呀！` 三个短感叹连起来才是一句反应）；
    #     ③ 没句号 + 太短 + 全文超上限 ⇒ 切（保持改造前行为，不在这里发明新策略）。
    #   ⚠️ 第一版写的是"取最靠前的够长切点"，被 `s7_event_speech A11` 当场判红：
    #      它把 `诶？！好舒服呀。后面还有好多话要说呢。` 整句留下了，说明
    #      **"句号优先"这条语义不能丢**（`A11` 守的是既有契约，不是绊脚石）。
    ends = _sentence_ends(t)          # ★ 第145轮：与另一条链共用一处实现
    if ends:
        _periods = [i for i in ends if t[i] == u'。']
        if _periods:
            _p = _periods[0]
            pick = _p
            for i in ends:
                if i > _p:
                    break
                head = t[:i] if t[i] == '\n' else t[:i + 1]
                if len(head.strip()) >= MIN_FIRST_CHARS:
                    pick = i
                    break
        else:
            i = ends[0]
            head = t[:i] if t[i] == '\n' else t[:i + 1]
            pick = i if (len(head.strip()) >= MIN_FIRST_CHARS
                         or len(t) > max_chars) else None
        if pick is not None:
            t = t[:pick] if t[pick] == '\n' else t[:pick + 1]
    t = t.strip()
    if len(t) > max_chars:
        t = _hard_cut(t, max_chars)
    t = t.strip()
    if not re.search(r'[0-9A-Za-z\u4e00-\u9fff]', t):
        return ""
    return t


def fit_sentences(text, max_chars=AUTO_SPEAK_MAX_CHARS):
    """取"不超过 max_chars 的**最长完整句群**"；一句都放不下时退回硬截。

    ## 为什么需要第二个函数（而不是复用 `first_sentence`）

    两条链要的东西**不一样**：

    | 链 | 语义 | 上限 |
    |---|---|---|
    | 事件反应 `first_sentence` | **只要一句**（触觉反应不该是小作文） | 24 |
    | 主动搭话 `fit_sentences`  | **能说多少说多少，但必须说完整** | 40 |

    第136轮实测：把主动搭话换成 `first_sentence(t, 40)`，98 条真实回复里 **21 条**被切短，
    平均长度 15.4 → 12.5 字，丢的正是"追问一句 / 补一句在意"这层 ——
    而那恰恰是主动搭话里最有人味的部分。反过来，旧的内联实现（整段 + 40 字硬截）
    在 98 条里有 **11 条吊尾巴**（断在「我在这边听」「叫豆豆是吧……我记得你有时候会给它点吃」这种半句上）。

    ⇒ 这个函数两个毛病都不沾：**长度上限守住，且切点一定落在句末**。

    ## 旧内联实现被取代

    `main.start_autonomous_speech` 里原来有一段自己写的 8 行截断
    （`for sep in ('\\n','。','！','？','!','?')` + `if len(text) > 40: text = text[:40]`）。
    它和本模块的实现**从来就不是同一份**（sep 顺序不同、一个 `\\n` 优先一个句号优先、
    一个有 MIN 规则一个没有）—— 原注释写的"同源"是假断言，第135轮已改正注释，
    第136轮把那段删掉、改调本函数。
    """
    if not isinstance(text, str):
        return ""
    t = text.strip()
    if not t:
        return ""
    t = t.strip('"\'“”「」『』《》').strip()
    if not t:
        return ""
    ends = _sentence_ends(t)          # ★ 第145轮：与另一条链共用一处实现
    # 放得下（且不是"切完只剩几个字"）的切点
    ok = []
    for i in ends:
        head = t[:i] if t[i] == '\n' else t[:i + 1]
        if len(head) <= max_chars:
            ok.append(i)
    if ok:
        pick = ok[-1]
        head = t[:pick] if t[pick] == '\n' else t[:pick + 1]
        if len(head.strip()) >= MIN_FIRST_CHARS or len(t) <= max_chars:
            t = head
        elif len(t) > max_chars:
            t = _hard_cut(t, max_chars)
    elif len(t) > max_chars:
        # 连一个句末标点都没有（或第一个就超出上限）⇒ 只能硬截，这里是**唯一**的兜底
        t = _hard_cut(t, max_chars)
    t = t.strip()
    if not re.search(r'[0-9A-Za-z\u4e00-\u9fff]', t):
        return ""
    return t


